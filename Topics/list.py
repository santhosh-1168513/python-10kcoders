list = [10, 20, 30, 40, 50]
print(list)
#append() method is used to add an element to the end of the list.
list.append(60)
print(list)
#insert() method is used to add an element at a specific index in the list.
list.insert(2, 25)
print(list)
#extend() method is used to add multiple elements to the end of the list.
list.extend([70, 80,90])
print(list)
#clear() method is used to remove all elements from the list.
list.clear()
print(list) 
